recollection, the ability to communicate, and understand that she is under a legal duty to
tell the truth. These factors appear to be met -- Sue has personal knowledge of her
interaction with Pam and appears to have a present recollection of the
interaction. Furthermore, there is nothing to indicate that she lacks the ability to
communicate or that she doesn''t understand her legal duty to tell the truth. Sue is
competent to testify.
